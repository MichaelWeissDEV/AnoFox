/**
 * Generates src/core/domain-utils/psl-data.ts from the vendored Public Suffix List.
 *   node scripts/build-psl.mjs                (uses vendor/psl/public_suffix_list.dat)
 *   node scripts/build-psl.mjs --update       (first downloads the current list from publicsuffix.org)
 *
 * The list is MPL-2.0 (see vendor/psl/README.md). Rules are converted to ASCII (punycode) because the extension only ever
 * sees URL.hostname values. Both the ICANN and the PRIVATE sections are included: browsers treat private suffixes such as
 * github.io or blogspot.com as site boundaries too, which is what the cookie vault and third-party logic need.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { domainToASCII } from 'node:url';

const SRC = new URL('../vendor/psl/public_suffix_list.dat', import.meta.url);
const OUT = new URL('../src/core/domain-utils/psl-data.ts', import.meta.url);

if (process.argv.includes('--update')) {
  const res = await fetch('https://publicsuffix.org/list/public_suffix_list.dat');
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  await writeFile(SRC, await res.text());
}

const text = await readFile(SRC, 'utf8');
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? 'unknown';
const commit = text.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? 'unknown';
const normal = [], wildcard = [], exception = [];
for (const raw of text.split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith('//')) continue;
  const rule = line.split(/\s+/)[0];
  const kind = rule.startsWith('!') ? 'exception' : rule.startsWith('*.') ? 'wildcard' : 'normal';
  const body = rule.replace(/^!/, '').replace(/^\*\./, '');
  const ascii = domainToASCII(body);
  if (!ascii) throw new Error(`cannot convert rule ${rule}`);
  (kind === 'exception' ? exception : kind === 'wildcard' ? wildcard : normal).push(ascii);
}
const uniq = (a) => [...new Set(a)].sort();
const body = `/**
 * GENERATED by scripts/build-psl.mjs from vendor/psl/public_suffix_list.dat - do not edit by hand.
 * Public Suffix List (https://publicsuffix.org/), licensed under the Mozilla Public License 2.0
 * (https://mozilla.org/MPL/2.0/). The unmodified source list is kept in vendor/psl/.
 */
export const PSL_VERSION = ${JSON.stringify(version)};
export const PSL_COMMIT = ${JSON.stringify(commit)};
/** normal rules, e.g. "co.uk" */
export const PSL_NORMAL = ${JSON.stringify(uniq(normal).join(' '))};
/** wildcard rules "*.x", stored as "x" */
export const PSL_WILDCARD = ${JSON.stringify(uniq(wildcard).join(' '))};
/** exception rules "!x", stored as "x" */
export const PSL_EXCEPTION = ${JSON.stringify(uniq(exception).join(' '))};
`;
await writeFile(OUT, body);
console.log(`PSL ${version}: ${normal.length} normal, ${wildcard.length} wildcard, ${exception.length} exception rules -> ${(body.length / 1024).toFixed(0)} KB`);
